#!/usr/bin/env python3
"""The node table in AGENT_FACTS.md, generated from the cluster.

The table used to be typed by hand and went stale (no ubt-k3s-07, the wrong
PROD node). Every column but the last is now read from `kubectl get nodes`;
the last column is a hand-written note that --write keeps as it is.

    kubectl --kubeconfig ~/.kube/bifrost-k3s.yaml get nodes -o json \
        | python3 scripts/k3s/node_table.py --check
    kubectl --kubeconfig ~/.kube/bifrost-k3s.yaml get nodes -o json \
        | python3 scripts/k3s/node_table.py --write

--check exits 1 and prints the differing rows when the generated columns in
the file are not what the cluster says. Ready and cordoned are left out on
purpose: gpu-server is a standby node and is normally off.

With --targets (the JSON of Prometheus /api/v1/targets) it also names every
node-exporter host that is neither a cluster node nor mentioned between the
`outside` markers. Hosts without an exporter (the two Win11 machines) cannot
be found this way.

The `postgres-role` label is a placement preference. The real primary is CNPG
`status.currentPrimary`.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

BEGIN = "<!-- node-table:begin (generated by scripts/k3s/node_table.py; edit only the last column) -->"
END = "<!-- node-table:end -->"
OUTSIDE_BEGIN = "<!-- node-table:outside:begin -->"
OUTSIDE_END = "<!-- node-table:outside:end -->"
HEADER = "| 节点 | IP | host-id | workload-pool | 线程 | 内存 GiB | 由标签得出 | 备注（手写） |"
RULE = "|------|----|---------|---------------|------|----------|------------|--------------|"
DEFAULT_FACTS = Path(__file__).resolve().parents[2] / "agent-config" / "AGENT_FACTS.md"


def mem_gib(quantity: str) -> str:
    units = {"Ki": 2**10, "Mi": 2**20, "Gi": 2**30, "Ti": 2**40}
    for suffix, mult in units.items():
        if quantity.endswith(suffix):
            return f"{int(quantity[:-2]) * mult / 2**30:.1f}"
    return f"{int(quantity) / 2**30:.1f}"


def traits(labels: dict[str, str]) -> str:
    out = []
    if "node-role.kubernetes.io/control-plane" in labels:
        out.append("控制面")
    if "node-role.kubernetes.io/etcd" in labels:
        out.append("etcd")
    role = labels.get("bifrost.io/postgres-role")
    if role == "primary":
        out.append("数据库主库标签")
    elif role:
        out.append(f"数据库{'备库' if role == 'standby' else role}标签")
    if labels.get("bifrost.io/wol") == "enabled":
        out.append("可唤醒")
    if labels.get("workload") == "gpu":
        out.append("GPU")
    if labels.get("storage.nfs/client") == "true":
        out.append("NFS 客户端")
    return "、".join(out) or "—"


def node_rows(nodes: dict) -> dict[str, list[str]]:
    rows = {}
    for item in nodes.get("items", []):
        meta, status = item["metadata"], item.get("status", {})
        labels = meta.get("labels", {})
        ip = next((a["address"] for a in status.get("addresses", []) if a["type"] == "InternalIP"), "—")
        cap = status.get("capacity", {})
        rows[meta["name"]] = [
            meta["name"],
            ip,
            labels.get("bifrost.io/host-id", "—"),
            labels.get("bifrost.io/workload-pool", "—"),
            str(cap.get("cpu", "—")),
            mem_gib(cap["memory"]) if "memory" in cap else "—",
            traits(labels),
        ]
    return rows


def split_block(text: str, begin: str, end: str) -> tuple[str, str, str]:
    if text.count(begin) != 1 or text.count(end) != 1 or text.index(begin) > text.index(end):
        raise SystemExit(f"node_table: need exactly one `{begin}` … `{end}` pair")
    head, rest = text.split(begin, 1)
    body, tail = rest.split(end, 1)
    return head, body, tail


def parse_table(body: str) -> dict[str, list[str]]:
    rows = {}
    for line in body.splitlines():
        if not line.startswith("|") or line in (HEADER, RULE) or set(line) <= set("|- "):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if cells and cells[0] != "节点":
            rows[cells[0]] = cells
    return rows


def render(generated: dict[str, list[str]], notes: dict[str, str]) -> str:
    lines = [HEADER, RULE]
    for name in sorted(generated):
        lines.append("| " + " | ".join(generated[name] + [notes.get(name, "")]) + " |")
    return "\n" + "\n".join(lines) + "\n"


def exporter_hosts(targets: dict) -> dict[str, str]:
    """IP -> scrape job, for every active node-exporter target."""
    hosts = {}
    for t in targets.get("data", targets).get("activeTargets", []):
        labels = t.get("labels", {})
        if labels.get("job") != "node-exporter":
            continue
        ip = labels.get("instance", "").rsplit(":", 1)[0]
        if ip:
            hosts[ip] = labels.get("job", "")
    return hosts


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--nodes", default="-", help="`kubectl get nodes -o json`; - is stdin (default)")
    ap.add_argument("--targets", help="Prometheus /api/v1/targets JSON, to name unlisted hosts")
    ap.add_argument("--facts", type=Path, default=DEFAULT_FACTS)
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--write", action="store_true")
    args = ap.parse_args(argv)

    raw = sys.stdin.read() if args.nodes == "-" else Path(args.nodes).read_text()
    generated = node_rows(json.loads(raw))
    if not generated:
        raise SystemExit("node_table: the node list is empty; refusing to compare against nothing")

    text = args.facts.read_text()
    head, body, tail = split_block(text, BEGIN, END)
    current = parse_table(body)
    notes = {name: cells[7] if len(cells) > 7 else "" for name, cells in current.items()}

    failed = False
    if args.write:
        args.facts.write_text(head + BEGIN + render(generated, notes) + END + tail)
        print(f"node_table: wrote {len(generated)} nodes to {args.facts}")
    else:
        for name in sorted(set(generated) | set(current)):
            want, have = generated.get(name), (current.get(name) or [])[:7] or None
            if want != have:
                failed = True
                print(f"node_table: {name}\n  cluster: {want}\n  file:    {have}")
        if not failed:
            print(f"node_table: {len(generated)} nodes match {args.facts.name}")

    if args.targets:
        _, outside, _ = split_block(args.facts.read_text(), OUTSIDE_BEGIN, OUTSIDE_END)
        cluster_ips = {row[1] for row in generated.values()}
        for ip in sorted(exporter_hosts(json.loads(Path(args.targets).read_text()))):
            if ip in cluster_ips:
                continue
            octet = ip.rsplit(".", 1)[-1]
            if ip not in outside and not re.search(rf"`\.{octet}`", outside):
                failed = True
                print(f"node_table: {ip} is scraped by Prometheus, is not a cluster node, and is not in the outside-the-cluster paragraph")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
