def probe_docs(v: dict) -> list[dict]:
    k = v["key"].lower()
    claim = f"td444-probe-{k}"
    docs = [
        pv(v, claim, v["path"], "default", claim, "nfs-fast", {"bifrost.io/td444-probe": "true"}),
        pvc(v, claim, "nfs-fast", claim, ns="default",
            labels={"bifrost.io/td444-probe": "true", "bifrost.io/td444-group": v["group"]}),
    ]
    for i, (uid, gid, fsgroup, subdir, subpath) in enumerate(v["probes"], start=1):
        probe_id = f"{k}-{i}-{uid}"
        for role, node, script in (("w", "@PROBE_NODE_A@", WRITER), ("r", "@PROBE_NODE_B@", READER)):
            sc = {"runAsUser": uid, "runAsGroup": gid, "runAsNonRoot": uid != 0,
                  "seccompProfile": {"type": "RuntimeDefault"}}
            if fsgroup is not None:
                sc["fsGroup"] = fsgroup
                sc["supplementalGroups"] = [fsgroup]
            mount = {"name": "target", "mountPath": "/mnt/target"}
            if subpath:
                mount["subPath"] = subpath
            docs.append({
                "apiVersion": "batch/v1",
                "kind": "Job",
                "metadata": {"name": f"td444-probe-{probe_id}-{role}", "namespace": "default",
                             "labels": {"bifrost.io/td444-probe": "true", "bifrost.io/td444-group": v["group"]}},
                "spec": {
                    "backoffLimit": 0,
                    "activeDeadlineSeconds": 300,
                    "ttlSecondsAfterFinished": 3600,
                    "template": {
                        "metadata": {"labels": {"bifrost.io/td444-probe": "true"}},
                        "spec": {
                            "restartPolicy": "Never",
                            "automountServiceAccountToken": False,
                            "nodeSelector": {"kubernetes.io/hostname": node},
                            "securityContext": sc,
                            "containers": [{
                                "name": "probe",
                                "image": PROBE_IMAGE,
                                "command": ["/bin/sh", "-c", script],
                                "env": [
                                    {"name": "PROBE_ID", "value": probe_id},
                                    {"name": "PROBE_SUBDIR", "value": subdir},
                                    {"name": "PROBE_TOKEN", "value": "@PROBE_TOKEN@"},
                                ],
                                "securityContext": {"allowPrivilegeEscalation": False,
                                                    "capabilities": {"drop": ["ALL"]}},
                                "resources": {"requests": {"cpu": "10m", "memory": "16Mi"},
                                              "limits": {"cpu": "100m", "memory": "32Mi"}},
                                "volumeMounts": [mount],
                            }],
                            "volumes": [{"name": "target", "persistentVolumeClaim": {"claimName": claim}}],
                        },
                    },
                },
            })
    return docs


def dump(docs: list[dict], section: str) -> str:
    body = "---\n".join(yaml.safe_dump(d, sort_keys=False, default_flow_style=False, width=1000) for d in docs)
    return HEADER.format(sec=section) + body


def render_all() -> dict[Path, str]:
    files: dict[Path, str] = {}
    groups: dict[str, list[dict]] = {}
    for v in VOLUMES:
        groups.setdefault(v["group"], []).append(v)
    for group, vols in groups.items():
        sec = GROUP_SECTIONS[group]
        d = HERE / group
        files[d / "pv.yaml"] = dump([pv(v, v["pv"], v["path"], v["ns"], v["name"], "nfs-fast") for v in vols], sec)
        files[d / "pvc.yaml"] = dump([pvc(v, v["name"], "nfs-fast", v["pv"]) for v in vols], sec)
        files[d / "pvc-dryrun.yaml"] = dump([pvc(v, f"td444-dryrun-{v['name']}", "nfs-fast", v["pv"]) for v in vols],
                                            "3.2 (server dry-run stand-in; differs from pvc.yaml only in metadata.name)")
        old = [v for v in vols if v["old_class"]]
        if old:
            files[d / "rollback-pvc.yaml"] = dump(
                [pvc(v, v["name"], v["old_class"], f"@OLD_PV_{v['key']}@") for v in old], "3.7 A / 3.6")
        for v in vols:  # one file per volume keeps every file under the 500-line ratchet
            files[d / f"probe-{v['key'].lower()}.yaml"] = dump(probe_docs(v), "3.5")
        for v in vols:
            rec = v.get("recovery")
            if rec:
                files[d / "recovery-pv.yaml"] = dump(
                    [pv(v, rec["pv"], rec["path"], v["ns"], v["name"], rec["storage_class"])], "3.7 B")
                files[d / "recovery-pvc.yaml"] = dump(
                    [pvc(v, v["name"], rec["storage_class"], rec["pv"])], "3.7 B")
    return files


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for path, text in sorted(render_all().items()):
        if args.check:
            if not path.exists() or path.read_text() != text:
                print(f"OUT OF DATE: {path.relative_to(HERE)}")
                bad += 1
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            print(f"wrote {path.relative_to(HERE)}")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
