def labels_for(v: dict, extra: dict | None = None) -> dict:
    out = {"bifrost.io/storage": "nfs-fast", "bifrost.io/td444-group": v["group"]}
    out.update(extra or {})
    return out


def pv(v: dict, name: str, path: str, claim_ns: str, claim_name: str, storage_class: str, extra_labels=None) -> dict:
    return {
        "apiVersion": "v1",
        "kind": "PersistentVolume",
        "metadata": {"name": name, "labels": labels_for(v, extra_labels)},
        "spec": {
            "capacity": {"storage": v["size"]},
            "accessModes": [v["mode"]],
            "volumeMode": "Filesystem",
            "persistentVolumeReclaimPolicy": "Retain",
            "storageClassName": storage_class,
            "mountOptions": list(MOUNT_OPTIONS),
            "nfs": {"server": "@NAS_IP@", "path": path},
            # namespace/name only, never a UID (runbook §0 point 2)
            "claimRef": {"namespace": claim_ns, "name": claim_name},
        },
    }


def pvc(v: dict, name: str, storage_class: str, volume_name: str, ns: str | None = None, labels=None) -> dict:
    meta = {"name": name, "namespace": ns or v["ns"]}
    lab = v["labels"] if labels is None else labels
    if lab:
        meta["labels"] = dict(lab)
    return {
        "apiVersion": "v1",
        "kind": "PersistentVolumeClaim",
        "metadata": meta,
        "spec": {
            "accessModes": [v["mode"]],
            "volumeMode": "Filesystem",
            "storageClassName": storage_class,
            "volumeName": volume_name,
            "resources": {"requests": {"storage": v["size"]}},
        },
    }


